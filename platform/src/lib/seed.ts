function d(offsetDays: number, hour = 18): string {
  const dt = new Date();
  dt.setUTCDate(dt.getUTCDate() + offsetDays);
  dt.setUTCHours(hour, 0, 0, 0);
  return dt.toISOString();
}
function end(dStart: string, hours = 3): string {
  return new Date(new Date(dStart).getTime() + hours * 3600_000).toISOString();
}

